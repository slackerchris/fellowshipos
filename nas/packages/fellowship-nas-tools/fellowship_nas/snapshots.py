"""Snapshot policies per share, carried out by Sanoid."""
import os

from .common import DAY, FnasError, HOUR, read_json, run, write_file
from . import backup, pools, shares


SANOID_FILE = "/etc/sanoid/sanoid.conf"
DEFAULT_POLICY = {"hourly": 24, "daily": 30, "monthly": 6}
BACKUP_POLICY = {"hourly": 0, "daily": 30, "monthly": 12}
MAX_KEPT = 1000
SNAPSHOT_MAX_AGE = {"hourly": 3 * HOUR, "daily": 2 * DAY, "monthly": 33 * DAY}


def sanoid_config(shares, backup_dataset):
    lines = ["# Generated by fnas from each pool's shares.json: changes here are overwritten", "",
             "[template_fellowship]", "autosnap = yes", "autoprune = yes",
             "frequently = 0", "weekly = 0", "yearly = 0",
             # One run gives its snapshots the same time, and Windows would list each
             # as a separate version. Sanoid runs every 15 minutes, in UTC, so these
             # keep the periods on different runs.
             "hourly_min = 0", "daily_hour = 23", "daily_min = 30",
             "monthly_mday = 1", "monthly_hour = 0", "monthly_min = 15"]
    for share in shares:
        if any(share["policy"].values()):
            lines += ["", f"[{share['dataset']}]", "use_template = fellowship"]
            lines += [f"{period} = {kept}" for period, kept in share["policy"].items()]
    if backup_dataset:
        # Backups arrive with their snapshots, and only need old ones cleared
        lines += ["", f"[{backup_dataset}]", "use_template = fellowship",
                  "recursive = yes", "autosnap = no"]
        lines += [f"{period} = {kept}" for period, kept in BACKUP_POLICY.items()]
    return "\n".join(lines) + "\n"


def write_sanoid_config():
    writable = [s for s in shares.list_shares() if not s["readonly"] and s["engine"] == "zfs"]
    settings = read_json(backup.BACKUP_FILE)
    target = None
    if settings and settings["target"] in pools.writable_pools():
        target = backup.backup_root(settings["target"])
    os.makedirs(os.path.dirname(SANOID_FILE), exist_ok=True)
    write_file(SANOID_FILE, sanoid_config(writable, target))


def list_snapshots(dataset):
    output = run("zfs", "list", "-Hp", "-t", "snapshot", "-o", "name,creation,used",
                 "-s", "creation", "-d", "1", dataset).stdout
    snapshots = []
    for line in output.splitlines():
        name, created, used = line.split("\t")
        snapshots.append({"name": name.split("@")[1], "created": int(created), "used": int(used)})
    return snapshots


def set_policy(name, hourly, daily, monthly):
    if hourly is None and daily is None and monthly is None:
        raise FnasError("nothing to change: pass --hourly, --daily or --monthly")
    share = shares.find_share(name)
    policy = share["policy"]
    for period, kept in (("hourly", hourly), ("daily", daily), ("monthly", monthly)):
        if kept is not None:
            if not 0 <= kept <= MAX_KEPT:
                raise FnasError(f"--{period} must be between 0 and {MAX_KEPT}")
            policy[period] = kept
    if share["engine"] != "zfs":
        raise FnasError(f"{share['pool']} has no snapshots on its engine")
    shares.save_settings(share["pool"], share)
    return policy
